// 🧠 ФУНКЦІЯ ВИБОРУ ПРОМПТУ
export const selectPrompt = (contextType, userGoal, userState) => {
  const basePrompt = AI_MENTOR_PROMPTS.SYSTEM_PROMPT;
  
  let specificPrompt = '';
  switch(contextType) {
    case CONTEXT_TYPES.GOAL_SETTING:
      specificPrompt = AI_MENTOR_PROMPTS.GOAL_SETTING;
      break;
    case CONTEXT_TYPES.MOTIVATION:
      specificPrompt = AI_MENTOR_PROMPTS.MOTIVATION;
      break;
    case CONTEXT_TYPES.MICRO_ACTIONS:
      specificPrompt = AI_MENTOR_PROMPTS.MICRO_ACTIONS;
      break;
    case CONTEXT_TYPES.LIFE_BALANCE:
      specificPrompt = AI_MENTOR_PROMPTS.LIFE_BALANCE;
      break;
    case CONTEXT_TYPES.BLOCK_ANALYSIS:
      specificPrompt = AI_MENTOR_PROMPTS.BLOCK_ANALYSIS;
      break;
    default:
      specificPrompt = AI_MENTOR_PROMPTS.MOTIVATION;
  }
  
  return `${basePrompt}\n\n${specificPrompt}`;
};

// 🤖 АНАЛІЗ КОНТЕКСТУ ПИТАННЯ
export const analyzeQuestionContext = (question) => {
  const q = question.toLowerCase();
  
  if (q.includes('ціль') || q.includes('хочу досягти') || q.includes('планую')) {
    return CONTEXT_TYPES.GOAL_SETTING;
  }
  if (q.includes('мотивація') || q.includes('натхнення') || q.includes('сили немає')) {
    return CONTEXT_TYPES.MOTIVATION;
  }
  if (q.includes('що робити') || q.includes('як діяти') || q.includes('кроки')) {
    return CONTEXT_TYPES.MICRO_ACTIONS;
  }
  if (q.includes('баланс') || q.includes('сфери життя') || q.includes('все встигти')) {
    return CONTEXT_TYPES.LIFE_BALANCE;
  }
  if (q.includes('страх') || q.includes('блок') || q.includes('не можу') || q.includes('заважає')) {
    return CONTEXT_TYPES.BLOCK_ANALYSIS;
  }
  
  return CONTEXT_TYPES.GENERAL;
};

// 📚 АНАЛІЗ ПОТРЕБИ В КУРСІ
export const analyzeCourseNeed = (question, conversationHistory = []) => {
  const q = question.toLowerCase();
  
  // Рекомендуємо курс тільки якщо є явні тригери
  for (const [courseKey, courseData] of Object.entries(AVAILABLE_COURSES)) {
    const hasMatchingTriggers = courseData.triggers.some(trigger => q.includes(trigger));
    if (hasMatchingTriggers) {
      return {
        course: courseData,
        reason: `Твоє питання показує, що ${courseData.name} може допомогти подолати цю ситуацію.`
      };
    }
  }
  
  return null;
};

